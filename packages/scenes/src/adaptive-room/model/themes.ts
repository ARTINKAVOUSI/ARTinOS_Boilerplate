/**
 * Theme = one coherent architectural mood: shell color + surface response,
 * light temperatures and a small object palette. Themes never change the
 * adaptive geometry logic — only material and light.
 */
export interface Theme {
  id: string;
  label: string;
  /** shell albedo */
  room: string;
  roughness: number;
  /** canvas / exterior backdrop */
  background: string;
  /** light colors */
  key: string;
  fill: string;
  hemiSky: string;
  hemiGround: string;
  /** overall light multiplier suggestion */
  lightIntensity: number;
  /** subject / ball palette */
  palette: string[];
}

